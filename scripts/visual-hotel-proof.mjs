import {createRequire} from 'node:module'
import {mkdir,writeFile} from 'node:fs/promises'
const require=createRequire(new URL('../../cruise-master-20261005/package.json',import.meta.url))
const {chromium}=require('@playwright/test')
const out=process.env.PROOF_OUT||'docs/cruise/os/visual-20261020/before'
await mkdir(out,{recursive:true})
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-webgl']})
const page=await browser.newPage({viewport:process.env.PROOF_MOBILE==='1'?{width:390,height:844}:{width:1440,height:900},deviceScaleFactor:1})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
page.on('console',m=>{if(m.type()==='error')console.log('browser error',m.text().slice(0,250))})
page.on('requestfailed',r=>console.log('request failed',r.url(),r.failure()?.errorText))
page.on('response',r=>{if(r.status()>=400)console.log('HTTP',r.status(),r.url())})
try{
 await page.goto(process.env.PROOF_URL||'http://127.0.0.1:3081/cruise/os?diagnostics=1',{waitUntil:'domcontentloaded',timeout:180000})
 console.log('document loaded');await page.screenshot({path:`${out}/entry.png`})
 await page.getByRole('button',{name:'Start the drive',exact:true}).click({timeout:60000})
 console.log('started')
 await page.waitForFunction(()=>window.__jeepNight?.()?.ready&&window.__miamiGeo?.()?.routeLength>0,null,{timeout:180000})
 await page.waitForTimeout(2000)
 await page.mouse.click(process.env.PROOF_MOBILE==='1'?180:700,100)
 await page.keyboard.press('Space')
 await page.evaluate(()=>window.__miamiInspect?.(67.5))
 await page.waitForTimeout(1200)
 await page.screenshot({path:`${out}/cockpit.png`})
 await page.keyboard.press('v');await page.waitForTimeout(2000)
 await page.screenshot({path:`${out}/coastal.png`})
 await page.getByRole('button',{name:'Menu',exact:true}).click()
 await page.getByRole('button',{name:'Places',exact:true}).click()
 await page.getByRole('button',{name:'Take a closer look',exact:true}).click()
 await page.waitForTimeout(3500)
 await page.screenshot({path:`${out}/colony.png`})
 await writeFile(`${out}/state.json`,JSON.stringify(await page.evaluate(()=>({drive:window.__jeepNight?.(),geo:window.__miamiGeo?.(),chunks:document.documentElement.dataset.miamiChunks,overflow:document.documentElement.scrollWidth>innerWidth,buttons:[...document.querySelectorAll('button')].map(b=>b.getAttribute('aria-label')||b.textContent)})),null,2))
 console.log(JSON.stringify({out,errors}))
}catch(e){await page.screenshot({path:`${out}/failure.png`});console.log('page errors',errors);throw e}finally{await browser.close()}
